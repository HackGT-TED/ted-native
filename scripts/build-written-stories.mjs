// Turns content/written-stories.json into the SQL that seeds public.written_stories.
// Usage: node scripts/build-written-stories.mjs > supabase/migrations/<number>_written_stories_seed.sql
// Every story is public domain; its text comes from Project Gutenberg (see source_url).
import { readFileSync } from 'node:fs';

const stories = JSON.parse(readFileSync(new URL('../content/written-stories.json', import.meta.url), 'utf8'));
const text = value => `'${String(value).replaceAll("'", "''")}'`;
const WORDS_PER_MINUTE = 150; // read aloud, not silently

const rows = stories.map(story => {
  const words = story.paragraphs.join(' ').split(/\s+/).filter(Boolean).length;
  return `  (${[
    text(story.slug), text(story.title), text(story.author), text(story.category), story.position,
    `${text(JSON.stringify(story.paragraphs))}::jsonb`, words, Math.max(1, Math.round(words / WORDS_PER_MINUTE)),
    text(story.source_title), text(story.source_url), text(story.cover_credit),
  ].join(', ')})`;
});

process.stdout.write(`-- Generated by scripts/build-written-stories.mjs from content/written-stories.json. Do not edit by hand.
insert into public.written_stories
  (slug, title, author, category, position, paragraphs, word_count, reading_minutes, source_title, source_url, cover_credit)
values
${rows.join(',\n')}
on conflict (slug) do update set
  title = excluded.title, author = excluded.author, category = excluded.category, position = excluded.position,
  paragraphs = excluded.paragraphs, word_count = excluded.word_count, reading_minutes = excluded.reading_minutes,
  source_title = excluded.source_title, source_url = excluded.source_url, cover_credit = excluded.cover_credit;
`);
